"""CLI regression coverage for independently managed Claude skills."""

import shutil
import subprocess
import sys
from pathlib import Path

import pytest

SOURCE = Path(__file__).resolve().parents[1]
SQUAD_MARKER = "<!-- Generated by Squad. Managed file: refreshed by `squad upgrade`; edit .squad/ instead. Claude projection v3. -->"


def put(root, name, content):
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


@pytest.fixture
def checkout(tmp_path):
    for name in ("scripts/agent/sync_adapters.py", "scripts/_template_common.py"):
        destination = tmp_path / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(SOURCE / name, destination)
    put(tmp_path, ".agents/skills/canonical/SKILL.md", "canonical skill\n")
    assert run(tmp_path).returncode == 0
    return tmp_path


def run(root, *args):
    return subprocess.run(
        [sys.executable, str(root / "scripts/agent/sync_adapters.py"), *args],
        capture_output=True,
        text=True,
        check=False,
    )


def add_squad(root):
    put(root, ".claude/skills/squad/SKILL.md", SQUAD_MARKER + "\nSquad skill\n")
    put(root, ".claude/skills/squad/support.txt", "user changes\n")
    return {p: p.read_bytes() for p in (root / ".claude/skills/squad").rglob("*") if p.is_file()}


def test_check_accepts_squad_and_sync_preserves_all_its_files(checkout):
    original = add_squad(checkout)
    result = run(checkout, "--check")
    assert result.returncode == 0, result.stderr
    put(checkout, ".claude/skills/canonical/stale.txt", "obsolete generated file\n")
    put(checkout, ".claude/skills/canonical/SKILL.md", "drift\n")
    assert run(checkout, "--check").returncode == 1
    result = run(checkout)
    assert result.returncode == 0, result.stderr
    assert run(checkout, "--check").returncode == 0
    assert not (checkout / ".claude/skills/canonical/stale.txt").exists()
    assert {p: p.read_bytes() for p in original} == original


@pytest.mark.parametrize("extra", ["unexpected/SKILL.md", "unexpected.txt"])
def test_unknown_entries_fail_without_sync_deleting_them(checkout, extra):
    put(checkout, ".claude/skills/" + extra, "preserve me\n")
    original = {p: p.read_bytes() for p in (checkout / ".claude/skills").rglob("*") if p.is_file()}
    assert run(checkout, "--check").returncode == 1
    result = run(checkout)
    assert result.returncode == 2
    assert "unrecognized" in result.stderr
    assert {p: p.read_bytes() for p in original} == original


def test_squad_marker_never_exempts_canonical_skill_drift(checkout):
    put(checkout, ".claude/skills/canonical/SKILL.md", SQUAD_MARKER + "\nchanged\n")
    assert run(checkout, "--check").returncode == 1


def test_symlink_cannot_claim_independent_ownership(checkout):
    external = checkout / "external"
    put(external, "SKILL.md", SQUAD_MARKER + "\nexternal skill\n")
    (checkout / ".claude/skills/squad").symlink_to(external, target_is_directory=True)
    assert run(checkout, "--check").returncode == 1
    assert run(checkout).returncode == 2
    assert (external / "SKILL.md").read_text().endswith("external skill\n")
